import { bahtText } from './baht-text';

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [110, 'หนึ่งร้อยสิบบาทถ้วน'],
    [1_000_000, 'หนึ่งล้านบาทถ้วน'],
    [1_000_001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [21_000_000, 'ยี่สิบเอ็ดล้านบาทถ้วน'],
    [25131.5, 'สองหมื่นห้าพันหนึ่งร้อยสามสิบเอ็ดบาทห้าสิบสตางค์'],
    [0.25, 'ยี่สิบห้าสตางค์'],
    [1609.35, 'หนึ่งพันหกร้อยเก้าบาทสามสิบห้าสตางค์'],
  ])('%s → %s', (amount, text) => {
    expect(bahtText(amount)).toBe(text);
  });
});
